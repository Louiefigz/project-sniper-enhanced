test("all nonselectable states have no video, no success claim and no automatic retry", () => {
  for (const state of ["unavailable", "pending-owned-execution", "pending-cleanup", "failed"] as const) {
    const html = renderToStaticMarkup(React.createElement(GuidedOpeningContent, { opening: pendingOpening(state) }));
    assert.doesNotMatch(html, /<video|<iframe|<button|<form|QC passed|Approved delivery/);
    assert.match(html, /No opening or delivery approval/);
    assert.match(html, /Subjective listening has not been performed/);
    assert.match(html, /not a completion estimate/);
  }
  const pending = renderToStaticMarkup(React.createElement(GuidedOpeningContent, { opening: pendingOpening("pending-owned-execution") }));
  assert.match(pending, /does not prove a worker is running/); assert.match(pending, /Unknown time is not zero/);
  assert.match(pending, /Do not start a duplicate render/);
  assert.doesNotMatch(pending, /Owned attempt to verified stop/);
});

