"""Representative synthetic SDR textures and actual selected-picture observations.

Selection records remain explicitly TEST-only; no isolated admission or source
rights are asserted. The ordinary encoder settings are never reduced for speed.
"""
from __future__ import annotations

import hashlib
from dataclasses import replace
from pathlib import Path
from unittest.mock import patch

from _guided_presenter_observation_fixture import selected_fixture
from _presenter_benchmark_io import BenchmarkIO
from graphics.presenter_layout_contract import PresenterCanvas, declaration_payload
from graphics.presenter_layout_geometry import compile_presenter_geometry
from guided_presenter_execution import OwnedPresenterExecution
from guided_presenter_observation import observe_presenter_asset
from guided_presenter_probe_identity import PresenterObservationRuntime
from producer_config import ENCODE

RATE = "30000/1001"
FRAMES = 30
SIZE = (1920, 1080)


class BenchmarkFixture:
    """One textured native base, a chart-like PNG and a moving video with real AAC."""

    def __init__(self, io: BenchmarkIO) -> None:
        """Generate and observe exact synthetic bytes within the already-started clock."""
        self.io = io
        self.runtime = PresenterObservationRuntime(io.ffprobe, str(io.root), io.clock, io.guard)
        self.base = self._generate("base")
        self.owners: dict[str, OwnedPresenterExecution] = {}
        for label in ("still", "video"):
            source = self._generate(label)
            self.owners[label] = self._owner(label, source)

    def _generate(self, label: str) -> Path:
        """Use moving detailed textures or colored grids, never a uniform speed fixture."""
        io, still = self.io, label == "still"
        path = io.root / (label + (".png" if still else ".mp4"))
        source = "testsrc" if still else "testsrc2"
        texture = f"{source}=size=1920x1080:rate={RATE}:duration=1.001,drawgrid=w=120:h=90:t=3:c=white@0.65"
        if label == "video":
            texture += ",hue=h=90"
        command = [io.ffmpeg.path, "-v", "error", "-nostdin", "-f", "lavfi", "-i", texture]
        if label == "video":
            command += ["-f", "lavfi", "-i", "sine=frequency=997:sample_rate=48000:duration=1.001"]
        command += self._encoding(still, label == "video") + [str(path)]
        io.stage = label + "-setup"
        io.execute(io.request(command))
        if label != "base":
            path = self._store(path)
        io.hold(path)
        return path

    def _encoding(self, still: bool, audio: bool) -> list[str]:
        """Explicit observed color/SAR; setup video uses the same x264 CRF/preset."""
        if still:
            return ["-frames:v", "1", "-an", "-vf", "format=rgb24,setsar=1,"
                "setparams=colorspace=gbr:color_primaries=bt709:color_trc=iec61966-2-1:range=full",
                "-c:v", "png", "-pix_fmt", "rgb24", "-update", "1"]
        return ["-frames:v", str(FRAMES), "-vf", "setsar=1,"
            "setparams=colorspace=bt709:color_primaries=bt709:color_trc=bt709:range=limited",
            "-c:v", ENCODE["vcodec"], "-crf", str(ENCODE["mezzanine_crf"]), "-preset", ENCODE["composite_preset"],
            "-pix_fmt", "yuv420p", "-colorspace", "bt709", "-color_primaries", "bt709",
            "-color_trc", "bt709", "-color_range", "tv", "-video_track_timescale", "30000",
            *(["-c:a", "aac", "-b:a", "128k", "-shortest"] if audio else ["-an"])]

    def _store(self, path: Path) -> Path:
        """Name actual generated bytes as required by the TEST selection contract."""
        digest = hashlib.sha256(path.read_bytes()).hexdigest()
        directory = self.io.root / ".sniper-external-media"
        directory.mkdir(exist_ok=True)
        destination = directory / f"{digest}.media"
        path.rename(destination)
        return destination

    def _owner(self, label: str, path: Path) -> OwnedPresenterExecution:
        """Observe selected bytes once, then bind an actual live manual-layout owner."""
        source = next(row for row in self.io.references if row.path == str(path))
        selected = selected_fixture(source, label == "still", f"TEST-1080p-{label}")
        declaration = declaration_payload(selected.geometry)
        declaration.update(enterFrames=5, exitFrames=5)
        declaration["mask"]["radiusPx"] = 24
        canvas = PresenterCanvas(*SIZE, FRAMES, "yuv420p")
        selected = replace(selected, geometry=compile_presenter_geometry(declaration, canvas, (0, FRAMES)))
        self.io.stage = label + "-selected-observation"
        with patch("guided_presenter_observation.run_text", self.io.execute):
            observed = observe_presenter_asset(selected, source, RATE, self.runtime)
        return OwnedPresenterExecution((selected,), (observed,), RATE, self.runtime)
